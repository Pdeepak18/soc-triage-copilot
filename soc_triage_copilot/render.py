"""Render a triage result as a markdown note an analyst can paste into a ticket."""

from __future__ import annotations

import json

from .models import Case
from .triage import TriageResult

VERDICT_LABEL = {
    "likely_true_positive": "Likely true positive",
    "needs_review": "Needs review",
    "likely_false_positive": "Likely false positive",
}


def to_markdown(case: Case, result: TriageResult, note: str | None = None) -> str:
    lines: list[str] = []
    add = lines.append

    add(f"# Triage note — {case.id}")
    add("")
    add(f"**{VERDICT_LABEL.get(result.verdict, result.verdict)}** "
        f"· risk **{result.risk_score}/100** · confidence **{result.confidence}** · "
        f"severity **{result.severity}**")
    add("")
    add(f"**Case:** {case.title}  ")
    add(f"**Source:** {case.source}  ")
    add(f"**Created:** {case.created_at:%Y-%m-%d %H:%M UTC}  ")
    add(f"**Alerts:** {len(case.alerts)} · **Techniques:** {len(result.findings)} · "
        f"**Indicators:** {sum(len(v) for v in result.iocs.values())}")
    add("")

    if note:
        add("## Analyst summary")
        add("")
        add(note)
        add("")

    add("## ATT&CK coverage of this case")
    add("")
    if result.findings:
        add("| Technique | Name | Tactic | Confidence | Evidence |")
        add("|---|---|---|---|---|")
        for finding in result.findings:
            evidence = "<br>".join(finding.evidence)
            add(f"| {finding.technique_id} | {finding.technique_name} | {finding.tactic} | "
                f"{finding.confidence} | {evidence} |")
    else:
        add("_No technique matched the alert text — review manually._")
    add("")

    add("## Timeline")
    add("")
    add("| Time (UTC) | Rule | Severity | Detail |")
    add("|---|---|---|---|")
    for entry in result.timeline:
        add(f"| {entry['time'][11:19]} | {entry['rule']} | {entry['severity']} | {entry['summary'][:120]} |")
    add("")

    if result.iocs:
        add("## Indicators")
        add("")
        for kind, values in result.iocs.items():
            add(f"- **{kind}** ({len(values)}): " + ", ".join(f"`{v}`" for v in values[:10]))
        add("")

    add("## Next steps")
    add("")
    for index, step in enumerate(result.next_steps, start=1):
        add(f"{index}. {step}")
    add("")
    add("---")
    add("_Generated by soc-triage-copilot. The verdict is rule-based; any LLM note is "
        "derived from the structured analysis above and should be reviewed before sending._")
    return "\n".join(lines)


def to_json(case: Case, result: TriageResult, note: str | None = None) -> str:
    payload = {
        "case": case.as_dict(),
        "triage": result.as_dict(),
        "note": note,
    }
    return json.dumps(payload, indent=2, default=str)
